// src/screens/admin/books/BookContentScreen.js
// Personalized section — read a generated piece, then decide whether students see it.
//
// Publishing exists ONLY here, never on the row that leads to it. Generated
// material is occasionally wrong — an OCR'd page produces a confident, wrong
// quiz answer — and once it is in front of students it is the platform's
// content, not the model's. So the only route to "published" runs through a
// screen where the content is on display.

import React, { useCallback, useState } from 'react';
import { View, ScrollView, Alert, ActivityIndicator } from 'react-native';
import { useFocusEffect } from '@react-navigation/native';
import { CircleCheck, Eye, EyeOff, Sparkles } from 'lucide-react-native';
import { T } from '../../parent/ParentApp/constants';
import { PressableScale } from '../../parent/ParentApp/anim';
import { AdminScreen, AdminHeader, AdminCard, AdminBadge, AdminErrorState, ListSkeleton, S, tone } from '../ui/kit';
import * as api from '../../../api/adminBooksApi';
import { sectionFor, Hair } from './BookBits';

export default function BookContentScreen({ route, navigation }) {
  const { contentId, kind, chapterTitle } = route.params || {};
  const meta = sectionFor(kind);
  const [state, setState] = useState({ loading: true, error: null, data: null });
  const [busy, setBusy] = useState(false);

  const load = useCallback(async () => {
    setState((s) => ({ ...s, loading: true, error: null }));
    try {
      const data = await api.getContent(contentId);
      setState({ loading: false, error: null, data });
    } catch (e) {
      setState({ loading: false, error: e?.message || 'Could not load this content', data: null });
    }
  }, [contentId]);

  useFocusEffect(useCallback(() => { load(); }, [load]));

  const d = state.data;
  const live = d?.status === 'published';

  const setStatus = async (status) => {
    setBusy(true);
    try {
      await api.setContentStatus(contentId, status);
      await load();
      Alert.alert(
        status === 'published' ? 'Published' : 'Back to draft',
        status === 'published'
          ? 'Students can see this — as long as the chapter and the book are also switched on.'
          : 'Students can no longer see this section.',
      );
    } catch (e) {
      Alert.alert('Could not update', e?.message || 'Please try again.');
    } finally { setBusy(false); }
  };

  return (
    <AdminScreen>
      <AdminHeader
        title={meta.label}
        subtitle={chapterTitle}
        onBack={() => navigation.goBack()}
        right={<AdminBadge toneKey={live ? 'emerald' : 'gold'} dot={false}>{live ? 'Live' : 'Draft'}</AdminBadge>}
      />

      {state.loading ? (
        <View style={{ paddingHorizontal: 16 }}><ListSkeleton rows={5} /></View>
      ) : state.error ? (
        <View style={{ padding: 16 }}><AdminErrorState message={state.error} onRetry={load} /></View>
      ) : (
        <>
          <ScrollView
            contentContainerStyle={{ padding: 16, paddingBottom: 150 }}
            showsVerticalScrollIndicator={false}
          >
            <Payload kind={kind} payload={d?.payload} />

            {!!d?.model && (
              <T w="semi" s={10.5} c={S.faint} style={{ textAlign: 'center', marginTop: 16 }}>
                Generated by {d.model}
              </T>
            )}
          </ScrollView>

          {/* Pinned, so the decision is always reachable without scrolling back. */}
          <View style={{
            position: 'absolute', left: 0, right: 0, bottom: 0,
            padding: 14, paddingBottom: 26,
            backgroundColor: S.card, borderTopWidth: 1, borderTopColor: S.hair,
          }}>
            <PressableScale
              onPress={() => setStatus(live ? 'draft' : 'published')}
              disabled={busy}
              accessibilityRole="button"
              accessibilityLabel={live ? 'Hide from students' : 'Publish to students'}
              style={{
                flexDirection: 'row', alignItems: 'center', justifyContent: 'center', gap: 8,
                paddingVertical: 15, borderRadius: 15,
                backgroundColor: live ? S.canvas : S.emerald,
                borderWidth: live ? 1 : 0, borderColor: S.border,
                opacity: busy ? 0.6 : 1,
              }}
            >
              {busy ? <ActivityIndicator size="small" color={live ? S.ink : '#FFFFFF'} />
                : live ? <EyeOff size={17} color={S.ink} strokeWidth={2.3} />
                : <Eye size={17} color="#FFFFFF" strokeWidth={2.3} />}
              <T w="xbold" s={14.5} c={live ? S.ink : '#FFFFFF'}>
                {live ? 'Hide from students' : 'Publish to students'}
              </T>
            </PressableScale>
            <T w="semi" s={10.5} c={S.faint} style={{ textAlign: 'center', marginTop: 8 }}>
              The chapter and the book must be switched on too.
            </T>
          </View>
        </>
      )}
    </AdminScreen>
  );
}

/** Renders each kind in the shape the student app will show it. */
function Payload({ kind, payload }) {
  if (!payload) return <T w="semi" s={13} c={S.muted}>This section is empty.</T>;

  if (kind === 'notes') {
    return (
      <View>
        {!!payload.summary && (
          <AdminCard style={{ marginBottom: 12, borderLeftWidth: 3, borderLeftColor: S.indigo }}>
            <T w="semi" s={13.5} c={S.ink} style={{ lineHeight: 21 }}>{payload.summary}</T>
          </AdminCard>
        )}
        {(payload.sections || []).map((s, i) => (
          <AdminCard key={i} style={{ marginBottom: 10 }}>
            <T w="xbold" s={14} c={S.ink}>{s.heading}</T>
            {(s.points || []).map((p, j) => (
              <View key={j} style={{ flexDirection: 'row', gap: 8, marginTop: 7 }}>
                <T w="bold" s={13} c={S.indigo}>•</T>
                <T w="semi" s={13} c={S.sub} style={{ flex: 1, lineHeight: 20 }}>{p}</T>
              </View>
            ))}
          </AdminCard>
        ))}
        {!!(payload.keyTerms || []).length && (
          <AdminCard>
            <T w="xbold" s={14} c={S.ink} style={{ marginBottom: 6 }}>Key terms</T>
            {payload.keyTerms.map((t, i) => (
              <View key={i} style={{ marginTop: 7 }}>
                <T w="xbold" s={12.5} c={S.indigo}>{t.term}</T>
                <T w="semi" s={12.5} c={S.sub} style={{ lineHeight: 19 }}>{t.meaning}</T>
              </View>
            ))}
          </AdminCard>
        )}
      </View>
    );
  }

  if (kind === 'resource') {
    return (
      <View>
        {(payload.items || []).map((it, i) => (
          <AdminCard key={i} style={{ marginBottom: 10 }}>
            <View style={{ flexDirection: 'row', alignItems: 'center', gap: 8, flexWrap: 'wrap' }}>
              <T w="xbold" s={13.5} c={S.ink} style={{ flex: 1, minWidth: 0 }} numberOfLines={2}>{it.title}</T>
              {!!it.type && <AdminBadge toneKey="emerald" dot={false}>{it.type}</AdminBadge>}
            </View>
            <T w="semi" s={13} c={S.sub} style={{ marginTop: 6, lineHeight: 20 }}>{it.body}</T>
          </AdminCard>
        ))}
      </View>
    );
  }

  if (kind === 'practice') {
    return (
      <View>
        {(payload.questions || []).map((q, i) => (
          <AdminCard key={i} style={{ marginBottom: 10 }}>
            <T w="xbold" s={13.5} c={S.ink} style={{ lineHeight: 20 }}>{i + 1}. {q.q}</T>
            {(q.marks || q.difficulty) && (
              <T w="semi" s={11} c={S.faint} style={{ marginTop: 3 }}>
                {[q.marks ? `${q.marks} marks` : null, q.difficulty].filter(Boolean).join(' · ')}
              </T>
            )}
            <Hair style={{ marginVertical: 9 }} />
            <T w="xbold" s={11.5} c={S.emerald}>ANSWER</T>
            <T w="semi" s={13} c={S.sub} style={{ marginTop: 3, lineHeight: 20 }}>{q.answer}</T>
          </AdminCard>
        ))}
      </View>
    );
  }

  // quiz — the correct option is marked, because a wrong answer key is the single
  // most damaging thing that can reach a student and it is invisible otherwise.
  return (
    <View>
      {(payload.questions || []).map((q, i) => (
        <AdminCard key={i} style={{ marginBottom: 10 }}>
          <T w="xbold" s={13.5} c={S.ink} style={{ lineHeight: 20 }}>{i + 1}. {q.q}</T>
          {(q.options || []).map((o, j) => {
            const right = j === q.answer;
            return (
              <View key={j} style={{
                flexDirection: 'row', alignItems: 'center', gap: 8,
                marginTop: 7, padding: 10, borderRadius: 11,
                backgroundColor: right ? S.emeraldSoft : S.canvas,
              }}>
                {right
                  ? <CircleCheck size={15} color={S.emerald} strokeWidth={2.4} />
                  : <View style={{ width: 15, height: 15, borderRadius: 99, borderWidth: 1.5, borderColor: S.border }} />}
                <T w={right ? 'xbold' : 'semi'} s={12.5} c={right ? S.emerald : S.sub} style={{ flex: 1, lineHeight: 18 }}>
                  {o}
                </T>
              </View>
            );
          })}
          {!!q.explanation && (
            <>
              <Hair style={{ marginVertical: 9 }} />
              <T w="semi" s={12} c={S.muted} style={{ lineHeight: 18 }}>{q.explanation}</T>
            </>
          )}
        </AdminCard>
      ))}
    </View>
  );
}
